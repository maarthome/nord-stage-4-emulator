#!/usr/bin/env python3
# ruff: noqa: E501
"""Dense rate laws of the Mod 1 types RM (4, 5) and A-WAH (6, 7) as Rust (`fx/fw_mod1_dense.rs`).

The dense ARM capture of the Fx1 slot (`tools/fx_mod2_dense.py --slot Fx1`,
`docs/research/data/fx-mod1-dense.csv`, piano unit) shows every `kFx1Amt` / `kFx1RateClkDiv` word
is linear between the 11 samples of `fx-mod1-laws` to float precision (3e-8 of the range), except
two rate words: the RM phase increment `c[-32]` (an exponential, up to 6.4 % off at v = 120) and
the A-WAH rate `c[-20]` (0.4 %). Those four series are exported as 44 knots. The words at v = 0 and 1
are the 11-sample ones: in the dense run the first values hit the type-switch default (the ARM
sends nothing for an unchanged value), the 11-sample capture has the settled words.

    python tools/fx_mod1_dense_gen.py [--check]
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fx_mod1_laws as m1
import fx_mod2_laws as ml

DENSE_CSV = ml.DATA / "fx-mod1-dense.csv"
RUST = ml.ROOT / "crates" / "nord-core" / "src" / "fx" / "fw_mod1_dense.rs"
#: `(type, dense dm_word, context offset)` of the series that need knots.
SERIES = ((4, 0xB0494, -32), (5, 0xB0494, -32), (6, 0xC1932, -20), (7, 0xC1932, -20))
#: Dense grid values at which the first two values are the type-switch default.
SETTLED = (0, 1)


def read_series() -> dict[tuple[int, int], dict[int, int]]:
    """`(type, dm_word) -> {value: word}` of the Rate rows."""
    out: dict[tuple[int, int], dict[int, int]] = {}
    with DENSE_CSV.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["id"] == "Rate":
                out.setdefault((int(r["type"]), int(r["dm_word"], 16)), {})[int(r["value"])] = int(
                    r["word"], 16
                )
    return out


def sample_word(ty: int, off: int, value: int) -> int:
    """The 11-sample word of the rate law of `ty` at the context offset `off`."""
    return m1.laws()[ty]["Rate"][off][1][ml.SAMPLES.index(value)]


def knots() -> list[int]:
    return sorted(max(read_series().values(), key=len))


def words(ty: int, dm: int, off: int) -> list[int]:
    ser = read_series()[(ty, dm)]
    return [sample_word(ty, off, v) if v in SETTLED else ser[v] for v in knots()]


TAIL = r"""/// The dense words of `(type, offset)`, if that rate word has knots.
pub(super) fn dense(ty: u8, off: i32) -> Option<&'static [u32; 44]> {
    RATES.iter().find(|d| d.0 == ty && d.1 == off).map(|d| &d.2)
}

/// Linear interpolation of `words` at `v` (`0..=127`) between the knots of the grid.
pub(super) fn eval(words: &[u32; 44], float: bool, v: u32) -> f32 {
    let v = v.min(127);
    let k = KNOTS
        .iter()
        .rposition(|&s| s <= v)
        .unwrap_or(0)
        .min(KNOTS.len() - 2);
    let t = (v - KNOTS[k]) as f32 / (KNOTS[k + 1] - KNOTS[k]) as f32;
    let (a, b) = (words[k], words[k + 1]);
    if float {
        let (a, b) = (f32::from_bits(a), f32::from_bits(b));
        a + (b - a) * t
    } else {
        let (a, b) = (a as i32 as f32, b as i32 as f32);
        a + (b - a) * t
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_knots_are_exact_and_the_ends_are_the_samples() {
        for (ty, off, w) in &RATES {
            let float = *off == -20;
            for (k, &v) in KNOTS.iter().enumerate() {
                let want = if float {
                    f32::from_bits(w[k])
                } else {
                    w[k] as i32 as f32
                };
                assert_eq!(eval(w, float, v), want, "type {ty} v {v}");
            }
        }
        assert!(dense(4, -32).is_some() && dense(6, -20).is_some());
        assert!(dense(8, -32).is_none());
    }
}
"""


def rust() -> str:
    out = [
        "//! Dense rate laws of the Mod 1 types RM (4, 5) and A-WAH (6, 7) (derived values).",
        "//!",
        "//! GENERATED by `python tools/fx_mod1_dense_gen.py` from `docs/research/data/fx-mod1-dense.csv`",
        "//! (ARM harness capture of the piano unit, `tools/fx_mod2_dense.py --slot Fx1`); do not edit.",
        "//! VERIFIED at every knot of `fw_mod2_dense::KNOTS`; linear between them (EMPIRICAL). The",
        "//! other Mod 1 words are linear between the 11 samples to 3e-8 of their range",
        "//! (`docs/research/fx-mod1-validation.md`), so only these four series need knots.",
        "",
        "use super::fw_mod2_dense::KNOTS;",
        "",
        "/// Knot words of one rate word: `(kFx1Type, context offset)` and the word at every knot.",
        "pub(super) type Dense = (u8, i32, [u32; 44]);",
        "",
        "#[rustfmt::skip]",
        "pub(super) const RATES: [Dense; 4] = [",
    ]
    for ty, dm, off in SERIES:
        out.append(f"    ({ty}, {off}, {[hex(w) for w in words(ty, dm, off)]}),".replace("'", ""))
    out += ["];", ""]
    return chr(10).join(out) + chr(10) + TAIL


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    text = rust()
    if ns.check:
        stale = not RUST.exists() or RUST.read_text(encoding="utf-8") != text
        print("stale" if stale else "up to date")
        return 1 if stale else 0
    RUST.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
