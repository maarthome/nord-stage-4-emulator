#!/usr/bin/env python3
"""Reduce the reverb colour captures to the committed delta table and the Rust words file.

`fx_rvb_color_capture.py` records, per `kRvbType`, the DSP words of the type switch (colour 0)
and of `kRvbColor` 1 and 2. The colour handler rewrites its block in full; the words that differ
from the type's own block are the colour delta. The delta is what the Rust port applies on top of
the committed type words, so the table stays correct whatever form the harness gives the rest.

    python tools/fx_rvb_colors.py --capture a.csv b.csv   # write data/fx-reverb-colors.csv
    python tools/fx_rvb_colors.py                         # write fx/fw_rvbm_colors.rs
    python tools/fx_rvb_colors.py --check                 # fail on a stale Rust file

Evidence and limits: `docs/research/fx-reverb-colors.md`.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs/research/data/fx-reverb-colors.csv"
RUST = ROOT / "crates/nord-core/src/fx/fw_rvbm_colors.rs"
FIELDS = "type,color,dm_word,word".split(",")
#: The types `fw_rvbm_words::TYPES` covers (6 has no trusted tap words, see the research note).
RUST_TYPES = (2, 3, 4, 5, 7, 8, 9, 10, 11)
#: Windows of `fw_rvbm.rs` (instance row, ring with the output filter words, type table): a
#: delta word outside them belongs to another module and is kept in the CSV only.
WINDOWS = ((0xC1A28, 0xC1A28 + 108), (0xE0000, 0xE0000 + 0xC60), (0x94370, 0x94370 + 0x90))


def in_window(addr: int) -> bool:
    return any(lo <= addr < hi for lo, hi in WINDOWS)


def reduce_rows(rows: list[dict[str, str]]) -> list[tuple[int, int, int, int]]:
    """`(type, color, address, word)` of every colour word that differs from the type block.

    The last message to an address wins (a handler may write a word twice); a colour word absent
    from the type block counts as different.
    """
    blocks: dict[tuple[int, int], dict[int, int]] = {}
    for r in rows:
        key = (int(r["type"]), int(r["color"]))
        blocks.setdefault(key, {})[int(r["dm_word"], 16)] = int(r["word"], 16)
    out = []
    for (t, c), words in sorted(blocks.items()):
        if c == 0:
            continue
        base = blocks.get((t, 0))
        if base is None:
            raise ValueError(f"type {t}: no colour 0 block")
        out += [(t, c, a, w) for a, w in sorted(words.items()) if base.get(a) != w]
    return out


def read_csv(path: Path) -> list[tuple[int, int, int, int]]:
    with path.open(encoding="utf-8", newline="") as fh:
        return [
            (int(r["type"]), int(r["color"]), int(r["dm_word"], 16), int(r["word"], 16))
            for r in csv.DictReader(fh)
        ]


def write_csv(path: Path, rows: list[tuple[int, int, int, int]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(FIELDS)
        w.writerows((t, c, f"{a:#x}", f"{v:#010x}") for t, c, a, v in rows)


def rust_file(rows: list[tuple[int, int, int, int]]) -> str:
    out = [
        "//! The colour deltas of the multi-tap reverb: the words `kRvbColor` 1 (Dark) and 2",
        "//! (Bright) change against the type's own block.",
        "//!",
        "//! GENERATED by `python tools/fx_rvb_colors.py`; do not edit. VERIFIED (ARM harness run,",
        "//! `tools/fx_rvb_color_capture.py`, `data/fx-reverb-colors.csv`): the words",
        "//! the colour handler of the synth unit L6 sends that differ from the type switch of the",
        "//! same type. Only words inside the windows of `fw_rvbm.rs` are kept.",
        "",
        "/// `(address, word)` deltas of `kRvbColor` 1 and 2 for each type of `words::TYPES`.",
        "#[rustfmt::skip]",
        f"pub(super) const COLOR_WORDS: [[&[(u32, u32)]; 2]; {len(RUST_TYPES)}] = [",
    ]
    for t in RUST_TYPES:
        out.append("    [")
        for c in (1, 2):
            sel = [(a, v) for tt, cc, a, v in rows if (tt, cc) == (t, c) and in_window(a)]
            pairs = [f"({a:#x}, {v:#010x})," for a, v in sel]
            out.append("        &[")
            out += ["            " + " ".join(pairs[k : k + 3]) for k in range(0, len(pairs), 3)]
            out.append("        ],")
        out.append("    ],")
    out += [
        "];",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::COLOR_WORDS;",
        "",
        "    #[test]",
        "    fn every_delta_is_sorted_unique_and_non_empty() {",
        "        for colors in COLOR_WORDS {",
        "            for d in colors {",
        "                assert!(!d.is_empty());",
        "                assert!(d.windows(2).all(|w| w[0].0 < w[1].0));",
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--capture", type=Path, nargs="+", help="raw capture CSVs; later files win")
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args(argv)
    if ns.capture:
        merged: dict[int, list[dict[str, str]]] = {}
        for p in ns.capture:
            with p.open(encoding="utf-8", newline="") as fh:
                per_type: dict[int, list[dict[str, str]]] = {}
                for r in csv.DictReader(fh):
                    per_type.setdefault(int(r["type"]), []).append(r)
            merged.update(per_type)
        write_csv(DATA, reduce_rows([r for t in sorted(merged) for r in merged[t]]))
    text = rust_file(read_csv(DATA))
    if ns.check:
        if not RUST.exists() or RUST.read_text(encoding="utf-8") != text:
            print("stale: fw_rvbm_colors.rs")
            return 1
        return 0
    RUST.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
