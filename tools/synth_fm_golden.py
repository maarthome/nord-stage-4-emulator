#!/usr/bin/env python3
"""Golden cases of the FM stages for the Rust port (`synth/fw_fm`).

    python tools/synth_fm_golden.py > crates/nord-core/src/synth/tests_fw_fm_golden.rs

Each case is a deterministic memory (the committed FM table, the committed P words, random lane
words, the nine image words listed in `IMAGE_WORDS`), the DM words the stage reads, and the words
the equation model ([synth_stage_fm](synth_stage_fm.py), equal to the listing interpreter and so to
`sharc-org`) leaves in the output buffer. Only derived values appear.
"""

from __future__ import annotations

import random
import struct
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth_fm_oracle as fo
import synth_fm_tables as ft
import synth_stage_fm as sf

DATA = Path(__file__).resolve().parents[1] / "docs" / "research" / "data"
# The nine image words the stages read outside the pokes (local ORG core 2 image, found with the
# listing interpreter): P block pointer, curve base, FIX scale, constants.
IMAGE_WORDS = {
    0xC0B72: 0xC2356,
    0xC15A8: 0xE0926,
    0xC1DF8: 0x1F,
    0xC1DF9: 0x1F,
    0xC1F76: 0xC169A,
    0xC1F79: 0x3C23D70A,
    0xC1F7A: 0x3C23D70A,
    0xC1F91: 0x3E4CCCCC,
    0xC1F92: 0x3E4CCCCC,
}
# seeds 1, 2: the committed ARM words of the type; seeds 11, 12: random lane words everywhere
CASES = [
    (stage, ty, seed)
    for stage in (1, 2)
    for ty, seeds in ((49, (1, 2, 11)), (50, (1, 12)), (51, (1,)), (52, (1, 11)), (53, (1, 12)))
    for seed in seeds
]
STRESS_SEEDS = (11, 12)


def f32(v: float) -> int:
    return struct.unpack("<I", struct.pack("<f", v))[0]


def memory(seed: int, table_type: int) -> dict[int, int]:
    """Pre-stage memory: pokes of the oracle driver plus the image words."""
    table = ft.load_csv(DATA / "synth-fm-tables.csv")[table_type]
    pre = fo.random_pokes(seed, table, fo.wo_words(table_type))
    mem = {**IMAGE_WORDS, **pre}
    if seed in STRESS_SEEDS:
        rng = random.Random(seed)
        i1, p = fo.REGS[1], 0xC169A
        for a in range(i1 - 29, i1 - 16):
            mem[a] = f32(rng.uniform(0.2, 2.0))
        for a in list(range(p - 32, p - 28)) + list(range(p - 16, p - 8)) + [p + 16, p + 17]:
            mem[a] = f32(rng.uniform(0.3, 1.2))
    return mem


def run(stage, seed: int, table_type: int) -> tuple[dict[int, int], dict[int, int]]:
    """`(memory before, words written)` of a stage model."""
    mem = memory(seed, table_type)
    pre = dict(mem)
    out: dict[int, int] = {}

    def write(a: int, w: int) -> None:
        mem[a] = w
        out[a] = w

    r = fo.REGS
    stage(lambda a: mem.get(a, 0), write, fo.I0_BASE, r[1], r[2], r[3])
    return pre, out


def case(stage: int, ty: int, seed: int) -> str:
    """One Rust struct literal."""
    pre, out = run({1: sf.stage1, 2: sf.stage2}[stage], seed, ty)
    r = fo.REGS
    i1, i2, i0 = r[1], r[2], fo.I0_BASE
    rd = lambda a: pre.get(a, 0)  # noqa: E731
    p = rd(i2 - 32)
    pair = lambda a: [rd(a), rd(a + 1)]  # noqa: E731
    acc = [[pair(0xC2346 + 8 * it + 2 * s) for s in range(4)] for it in range(2)]
    fields = {
        "stage": stage,
        "ty": ty,
        "p0": pair(i2 - 29),
        "ratio": [pair(p - 32), pair(p - 30)],
        "inc_scale": rd(i0 - 10),
        "pos": pair(i2 - 31),
        "x": pair(i2 - 5),
        "arm": [rd(i1 + o) for o in range(-29, -17)],
        "weights": [rd(p - 16 + j) for j in range(8)],
        "gain": pair(p + 16),
        "acc": acc,
        "out": [[out[i2 - 13 + 2 * k], out[i2 - 12 + 2 * k]] for k in range(4)],
    }  # fmt: skip
    return (
        "    Case {\n"
        + "".join(f"        {k}: {rust(v)},\n" for k, v in fields.items())
        + "    },\n"
    )


def rust(v) -> str:
    if isinstance(v, list):
        return "[" + ", ".join(rust(x) for x in v) + "]"
    return f"{v}" if isinstance(v, int) and v < 256 else f"0x{v:08x}"


def main() -> None:
    print("// @generated by tools/synth_fm_golden.py: do not edit.")
    print(
        "//! Golden cases of the FM stages (derived words only, Python model equal to the oracle)."
    )
    print()
    print("#[derive(Debug, Clone, Copy)]")
    print("pub struct Case {")
    for name, ty in (
        ("stage", "u8"), ("ty", "u8"), ("p0", "[u32; 2]"), ("ratio", "[[u32; 2]; 2]"),
        ("inc_scale", "u32"), ("pos", "[u32; 2]"), ("x", "[u32; 2]"), ("arm", "[u32; 12]"),
        ("weights", "[u32; 8]"), ("gain", "[u32; 2]"), ("acc", "[[[u32; 2]; 4]; 2]"),
        ("out", "[[u32; 2]; 4]"),
    ):  # fmt: skip
        print(f"    pub {name}: {ty},")
    print("}")
    print()
    print(f"pub const CASES: [Case; {len(CASES)}] = [")
    for c in CASES:
        print(case(*c), end="")
    print("];")
    print()
    print("#[test]")
    print("fn the_golden_table_has_the_generated_case_count() {")
    print(f"    assert_eq!(CASES.len(), {len(CASES)});")
    print("}")


if __name__ == "__main__":
    main()
